"""Source-free RapidOCR word probe for the isolated TATR/RapidTable trials.

The CLI draws its own raster. It accepts no PDF, gold, or arbitrary image input.
This module is evaluation support, not part of product extraction.
"""

from __future__ import annotations

import argparse
import base64
import csv
import hashlib
import importlib.metadata
import json
import math
import os
import re
import sys
import zipfile
from collections.abc import Sequence
from pathlib import Path
from typing import Any

OCR_REVISION = "rapidocr==3.10.0;PP-OCRv6-small;RapidAI-v3.10.0"
EXPECTED_LINES = ("NORTH SOUTH", "ALPHA BETA")
EXPECTED_WORDS = ("NORTH", "SOUTH", "ALPHA", "BETA")
LOCK_PATH = Path(__file__).parent / "fixtures" / "tatr_rapidocr_word_lock.json"
DEPENDENCY_LOCK_PATH = Path(__file__).parent / "fixtures" / "rapidtable_v3_runtime_lock.json"


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _canonical_name(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _check_hash(path: Path, expected: str) -> None:
    if not path.is_file() or sha256_file(path) != expected:
        raise ValueError(f"pinned asset differs: {path}")


def _verify_installed_record(dist: importlib.metadata.Distribution, root: Path) -> int:
    """Hash installed files, including copied models and binary extensions."""
    record = dist.read_text("RECORD")
    if not record:
        raise ValueError(f"missing installed RECORD: {dist.metadata['Name']}")
    count = 0
    for name, recorded_hash, recorded_size in csv.reader(record.splitlines()):
        path = Path(dist.locate_file(name)).resolve()
        if not recorded_hash and path.suffix == ".pyc" and "__pycache__" in path.parts:
            # pip records generated bytecode paths without source wheel hashes.
            continue
        if not path.is_relative_to(root) or not path.is_file():
            raise ValueError(f"installed RECORD path missing or escaped: {name}")
        if not recorded_hash:
            if Path(name).name != "RECORD":
                raise ValueError(f"installed RECORD lacks a file hash: {name}")
            continue
        algorithm, digest = recorded_hash.split("=", 1)
        if algorithm != "sha256":
            raise ValueError(f"unexpected installed RECORD hash: {name}")
        actual = base64.urlsafe_b64encode(bytes.fromhex(sha256_file(path))).rstrip(b"=").decode()
        if actual != digest or (recorded_size and path.stat().st_size != int(recorded_size)):
            raise ValueError(f"installed distribution file differs: {name}")
        count += 1
    if count == 0:
        raise ValueError(f"empty installed RECORD: {dist.metadata['Name']}")
    return count


def _verify_wheel_payload(wheel: zipfile.ZipFile, site_packages: Path) -> int:
    """Compare installed bytes with the pinned wheel, not just pip's RECORD."""
    count = 0
    for name in wheel.namelist():
        if name.endswith(("/", ".dist-info/RECORD")):
            continue
        path = (site_packages / name).resolve()
        if not path.is_relative_to(site_packages) or not path.is_file():
            raise ValueError(f"pinned wheel payload missing or escaped: {name}")
        digest = hashlib.sha256()
        with wheel.open(name) as source:
            for block in iter(lambda: source.read(1024 * 1024), b""):
                digest.update(block)
        if digest.hexdigest() != sha256_file(path):
            raise ValueError(f"installed file differs from pinned wheel: {name}")
        count += 1
    return count


def verify_runtime(runtime_root: Path, wheelhouse: Path, notices_root: Path) -> dict[str, Any]:
    """Verify the headless-only OCR environment and its cached wheel closure."""
    runtime_root, wheelhouse = runtime_root.resolve(strict=True), wheelhouse.resolve(strict=True)
    notices_root = notices_root.resolve(strict=True)
    if Path(sys.prefix).resolve() != runtime_root:
        raise ValueError("run with the OCR runtime's own Python interpreter")
    site_packages = runtime_root / "Lib" / "site-packages"
    lock = json.loads(LOCK_PATH.read_text(encoding="utf-8"))
    _check_hash(DEPENDENCY_LOCK_PATH, lock["dependency_wheel_lock_sha256"])
    dependency_lock = json.loads(DEPENDENCY_LOCK_PATH.read_text(encoding="utf-8"))
    exclusions = {_canonical_name(name) for name in lock["excluded_dependency_wheels"]}
    wheels = [row for row in dependency_lock["wheels"]
              if _canonical_name(row["package"]) not in exclusions]
    expected_names = {_canonical_name(row["package"]) for row in wheels}
    installed = {
        _canonical_name(dist.metadata["Name"]): dist
        for dist in importlib.metadata.distributions(path=[str(site_packages)])
    }
    if set(installed) != expected_names | {"pip", "setuptools"}:
        raise ValueError("OCR runtime has missing or unexpected installed distributions")
    verified_files = 0
    wheel_payload_files = 0
    record_hashes: dict[str, str] = {}
    for row in wheels:
        wheel_path = wheelhouse / row["filename"]
        _check_hash(wheel_path, row["sha256"])
        if wheel_path.stat().st_size != row["size_bytes"]:
            raise ValueError(f"wheel size differs: {wheel_path}")
        with zipfile.ZipFile(wheel_path) as wheel:
            for notice in row["notices"]:
                if hashlib.sha256(wheel.read(notice["path"])).hexdigest() != notice["sha256"]:
                    raise ValueError(f"wheel notice differs: {notice['path']}")
            wheel_payload_files += _verify_wheel_payload(wheel, site_packages)
        dist = installed[_canonical_name(row["package"])]
        if dist.version != row["version"]:
            raise ValueError(f"installed version differs: {row['package']}")
        verified_files += _verify_installed_record(dist, runtime_root)
        record_hashes[row["package"]] = hashlib.sha256(dist.read_text("RECORD").encode()).hexdigest()
    if importlib.metadata.version("rapidocr") != lock["rapidocr_version"]:
        raise ValueError("RapidOCR version differs")
    if importlib.metadata.version("onnxruntime") != lock["onnxruntime_version"]:
        raise ValueError("ONNX Runtime version differs")
    rapidocr_dir = site_packages / "rapidocr"
    if not rapidocr_dir.is_dir() or (site_packages / "opencv_python-5.0.0.93.dist-info").exists():
        raise ValueError("expected headless-only OpenCV runtime")
    _check_hash(wheelhouse / lock["rapidocr_wheel"]["filename"], lock["rapidocr_wheel"]["sha256"])
    for name, expected in lock["package_files"].items():
        path = rapidocr_dir / name if name == "default_models.yaml" else site_packages / name
        _check_hash(path, expected)
    for name, model in lock["models"].items():
        _check_hash(rapidocr_dir / "models" / name, model["sha256"])
    for notice in lock["external_notices"]:
        _check_hash(notices_root / notice["name"], notice["sha256"])
    return {
        "runtime_root": str(runtime_root),
        "wheelhouse": str(wheelhouse),
        "notices_root": str(notices_root),
        "dependency_wheel_lock_sha256": lock["dependency_wheel_lock_sha256"],
        "ocr_lock_sha256": sha256_file(LOCK_PATH),
        "wheel_count": len(wheels),
        "installed_record_files_verified": verified_files,
        "installed_wheel_payload_files_verified": wheel_payload_files,
        "installed_record_sha256": record_hashes,
        "model_sha256": {name: item["sha256"] for name, item in lock["models"].items()},
        "rapidocr_wheel_sha256": lock["rapidocr_wheel"]["sha256"],
        "installed_hashed_wheel_payload_verified": True,
        "generated_bytecode_excluded": True,
        "opencv_package": "opencv-python-headless==5.0.0.93",
        "external_notices_sha256": {item["name"]: item["sha256"] for item in lock["external_notices"]},
    }


def _polygon(value: Any, image_size: tuple[int, int]) -> list[list[float]]:
    width, height = image_size
    if hasattr(value, "tolist"):
        value = value.tolist()
    if not isinstance(value, Sequence) or len(value) != 4:
        raise ValueError("OCR word requires a four-point polygon")
    polygon: list[list[float]] = []
    for point in value:
        if not isinstance(point, Sequence) or len(point) != 2:
            raise ValueError("OCR word polygon point has wrong shape")
        x, y = point
        if (not isinstance(x, (int, float)) or isinstance(x, bool)
                or not isinstance(y, (int, float)) or isinstance(y, bool)
                or not math.isfinite(x) or not math.isfinite(y)
                or not 0 <= x <= width or not 0 <= y <= height):
            raise ValueError("OCR word polygon exceeds the image or is nonfinite")
        polygon.append([float(x), float(y)])
    area = abs(sum(
        polygon[i][0] * polygon[(i + 1) % 4][1]
        - polygon[(i + 1) % 4][0] * polygon[i][1]
        for i in range(4)
    )) / 2
    if area <= 0:
        raise ValueError("OCR word polygon has no area")
    turns = [
        (polygon[(i + 1) % 4][0] - polygon[i][0])
        * (polygon[(i + 2) % 4][1] - polygon[(i + 1) % 4][1])
        - (polygon[(i + 1) % 4][1] - polygon[i][1])
        * (polygon[(i + 2) % 4][0] - polygon[(i + 1) % 4][0])
        for i in range(4)
    ]
    if any(turn == 0 for turn in turns) or min(turns) < 0 < max(turns):
        raise ValueError("OCR word polygon is not a convex quadrilateral")
    return polygon


def rapidocr_words_to_tatr_tokens(result: Any, image_size: tuple[int, int]) -> list[dict[str, Any]]:
    """Preserve RapidOCR's explicit line/word order, word quads and raw scores."""
    width, height = image_size
    if width <= 0 or height <= 0:
        raise ValueError("invalid OCR raster dimensions")
    lines = getattr(result, "txts", None)
    line_boxes = getattr(result, "boxes", None)
    line_scores = getattr(result, "scores", None)
    word_lines = getattr(result, "word_results", None)
    if (lines is None or line_boxes is None or line_scores is None or word_lines is None
            or not lines or not len(lines) == len(line_boxes) == len(line_scores) == len(word_lines)):
        raise ValueError("RapidOCR line and word results are absent or misaligned")
    tokens: list[dict[str, Any]] = []
    for line_index, (line, line_box, line_score, words) in enumerate(
        zip(lines, line_boxes, line_scores, word_lines, strict=True)
    ):
        if not isinstance(line, str) or not line.strip() or not words:
            raise ValueError("RapidOCR line has no recognized words")
        _polygon(line_box, image_size)
        if (not isinstance(line_score, (int, float)) or isinstance(line_score, bool)
                or not math.isfinite(line_score) or not 0 <= line_score <= 1):
            raise ValueError("invalid RapidOCR line score")
        concatenated = ""
        for word_index, item in enumerate(words):
            if not isinstance(item, Sequence) or len(item) != 3:
                raise ValueError("RapidOCR word result has wrong shape")
            text, confidence, raw_polygon = item
            if not isinstance(text, str) or not text or any(char.isspace() for char in text):
                raise ValueError("RapidOCR did not return one nonempty word")
            if (not isinstance(confidence, (int, float)) or isinstance(confidence, bool)
                    or not math.isfinite(confidence) or not 0 <= confidence <= 1):
                raise ValueError("invalid RapidOCR reported word score")
            polygon = _polygon(raw_polygon, image_size)
            left = min(point[0] for point in polygon)
            top = min(point[1] for point in polygon)
            right = max(point[0] for point in polygon)
            bottom = max(point[1] for point in polygon)
            if left >= right or top >= bottom:
                raise ValueError("RapidOCR word bounding box has no area")
            tokens.append({
                "text": text,
                "bbox": [left, top, right, bottom],
                "ocr_polygon": polygon,
                "source": "ocr_word",
                "reading_order": len(tokens),
                "source_token_id": f"rapidocr:l{line_index}:w{word_index}",
                "ocr_engine": "RapidOCR/ONNXRuntime-CPU",
                "ocr_revision": OCR_REVISION,
                "ocr_confidence": float(confidence),
                "ocr_confidence_basis": "RapidOCR word_results reported score; uncalibrated",
                "ocr_line_score": float(line_score),
            })
            concatenated += text
        if "".join(line.split()) != concatenated:
            raise ValueError("RapidOCR words do not reconstruct their line")
    return tokens


def run_synthetic(*, runtime_root: Path, wheelhouse: Path, notices_root: Path, font_path: Path,
                  output_dir: Path) -> dict[str, Any]:
    """Probe fixed English words without a document or gold path."""
    runtime = verify_runtime(runtime_root, wheelhouse, notices_root)
    font_path = font_path.resolve(strict=True)
    import numpy as np
    import onnxruntime as ort
    from PIL import Image, ImageDraw, ImageFont
    from rapidocr import RapidOCR

    from product_eval.tatr_cell_compat import prepare_word_tokens

    image = Image.new("RGB", (1100, 340), "white")
    draw = ImageDraw.Draw(image)
    font = ImageFont.truetype(str(font_path), 58)
    draw.text((50, 60), EXPECTED_LINES[0], font=font, fill="black")
    draw.text((50, 190), EXPECTED_LINES[1], font=font, fill="black")
    model_dir = runtime_root / "Lib" / "site-packages" / "rapidocr" / "models"
    engine = RapidOCR(params={
        "Det.lang_type": "en", "Rec.lang_type": "en",
        "Det.model_path": str(model_dir / "PP-OCRv6_det_small.onnx"),
        "Cls.model_path": str(model_dir / "ch_ppocr_mobile_v2.0_cls_mobile.onnx"),
        "Rec.model_path": str(model_dir / "PP-OCRv6_rec_small.onnx"),
        "EngineConfig.onnxruntime.intra_op_num_threads": 4,
        "EngineConfig.onnxruntime.inter_op_num_threads": 1,
        "EngineConfig.onnxruntime.use_cuda": False,
        "EngineConfig.onnxruntime.use_dml": False,
    })
    result = engine(np.asarray(image), return_word_box=True, return_single_char_box=False)
    providers = {
        part: getattr(engine, part).session.session.get_providers()
        for part in ("text_det", "text_cls", "text_rec")
    }
    if any(selected != ["CPUExecutionProvider"] for selected in providers.values()):
        raise ValueError("a RapidOCR model session is not CPU-only")
    tokens = rapidocr_words_to_tatr_tokens(result, image.size)
    prepared = prepare_word_tokens(tokens, image.size)
    if tuple(result.txts) != EXPECTED_LINES or tuple(token["text"] for token in tokens) != EXPECTED_WORDS:
        raise ValueError("synthetic OCR text differs from the known four words")
    for pair in ((0, 1), (2, 3)):
        if tokens[pair[0]]["bbox"][2] >= tokens[pair[1]]["bbox"][0]:
            raise ValueError("synthetic adjacent words lack separate geometry")
    if len(prepared) != 4:
        raise ValueError("TATR did not accept four OCR word tokens")
    output_dir.mkdir(parents=True, exist_ok=False)
    image_path = output_dir / "synthetic.png"
    image.save(image_path)
    receipt = {
        "status": "source_free_word_token_pass",
        "scope": "one artificial raster; no selected PDF, gold, product extraction or parser score",
        "source_pdfs_opened": 0,
        "gold_records_opened": 0,
        "runtime": runtime,
        "source_sha256": sha256_file(Path(__file__)),
        "font_sha256": sha256_file(font_path),
        "image_sha256": sha256_file(image_path),
        "image_size": list(image.size),
        "lines": list(result.txts),
        "line_boxes": result.boxes.tolist(),
        "line_scores": list(result.scores),
        "word_tokens": tokens,
        "tatr_prepared_token_count": len(prepared),
        "providers_available": ort.get_available_providers(),
        "providers_selected": providers,
        "confidence_caveat": "RapidOCR 3.10.0 word_results scores are raw reported scores, not calibrated word probabilities; grouped-word aggregation is not established.",
        "runtime_boundary": "21 OCR dependency wheels, hashed installed payloads and staged upstream notices verified; generated .pyc, bootstrap pip/setuptools, and host system DLLs are outside this closure.",
    }
    encoded = json.dumps(receipt, indent=2, sort_keys=True) + "\n"
    receipt_path = output_dir / "receipt.json"
    with os.fdopen(os.open(receipt_path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), "w", encoding="utf-8") as stream:
        stream.write(encoded)
    return {"receipt": str(receipt_path), "sha256": sha256_file(receipt_path),
            "word_count": len(tokens), "providers": providers}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runtime-root", required=True, type=Path)
    parser.add_argument("--wheelhouse", required=True, type=Path)
    parser.add_argument("--notices-root", required=True, type=Path)
    parser.add_argument("--font", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    args = parser.parse_args()
    print(json.dumps(run_synthetic(runtime_root=args.runtime_root, wheelhouse=args.wheelhouse,
                                   notices_root=args.notices_root,
                                   font_path=args.font, output_dir=args.output_dir)))


if __name__ == "__main__":
    main()
